def _check_node_dict(result_scores: dict, golden: dict, label: str) -> None:
    """Extract (layer, neuron) keys from AtPNode result and assert_close vs golden."""
    result_keyed: dict[tuple, float] = {}
    for atp_node, score in result_scores.items():
        nd = atp_node.node
        k = (nd.layer, nd.neuron)
        result_keyed[k] = score

    assert set(result_keyed.keys()) == set(golden.keys()), (
        f"{label}: key mismatch\n"
        f"  result keys: {sorted(result_keyed.keys())}\n"
        f"  golden keys: {sorted(golden.keys())}"
    )
    for k, gold_val in golden.items():
        res_val = result_keyed[k]
        torch.testing.assert_close(
            torch.tensor(res_val),
            torch.tensor(gold_val),
            rtol=0,
            atol=0,
            msg=f"{label} key={k}: got {res_val!r}, expected {gold_val!r}",
        )


def _check_edge_dict(circuit_edges: dict, golden: dict, label: str) -> None:
    """Extract canonical keys from circuit.edges and assert_close vs golden."""
    result_keyed: dict[tuple, float] = {}
    for edge, score in circuit_edges.items():
        w = edge.writer.node
        r = edge.reader.node
        if w.kind == "sae_error":
            k = ((w.layer, None), (r.layer, r.neuron))
        else:
            k = ((w.layer, w.neuron), (r.layer, r.neuron))
        result_keyed[k] = score

    assert set(result_keyed.keys()) == set(golden.keys()), (
        f"{label}: key mismatch\n"
        f"  result has {len(result_keyed)} edges, golden has {len(golden)} edges"
    )
    for k, gold_val in golden.items():
        res_val = result_keyed[k]
        torch.testing.assert_close(
            torch.tensor(res_val),
            torch.tensor(gold_val),
            rtol=0,
            atol=0,
            msg=f"{label} edge={k}: got {res_val!r}, expected {gold_val!r}",
        )


